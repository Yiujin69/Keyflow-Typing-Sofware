export const ALL_LESSONS: Lesson[] = CURRICULUM.flatMap((unit) => unit.lessons);
export const TOTAL_LESSONS = ALL_LESSONS.length;

const lessonIndex = new Map(ALL_LESSONS.map((lesson) => [lesson.id, lesson]));

export function getLesson(id: string): Lesson | undefined {
  return lessonIndex.get(id);
}

export function getUnit(id: string): Unit | undefined {
  return CURRICULUM.find((unit) => unit.id === id);
}

export function lessonNumber(id: string): number {
  const index = ALL_LESSONS.findIndex((lesson) => lesson.id === id);
  return index < 0 ? 0 : index + 1;
}

export function lessonAccent(lesson: Lesson): string {
  return getUnit(lesson.unitId)?.accent ?? '#6366f1';
}

export function nextLessonId(completed: Record<string, { completedAt: number | null }>): string {
  const next = ALL_LESSONS.find((lesson) => !completed[lesson.id]?.completedAt);
  return (next ?? ALL_LESSONS[ALL_LESSONS.length - 1]).id;
}

export function unitProgress(unit: Unit, completed: Record<string, { completedAt: number | null }>) {
  const done = unit.lessons.filter((lesson) => completed[lesson.id]?.completedAt).length;
  return { done, total: unit.lessons.length, ratio: done / unit.lessons.length };
}
